-- Bump this whenever PER_MODEL_SCRIPT_TEMPLATE changes: heroes carrying
-- an older version are upgraded automatically (keeping their data)
-- the next time this Global script loads or they're spawned.
local SCRIPT_VERSION = 3

-- Keys copied from an old hero's saved data into the upgraded script.
local STATE_KEYS = {
  "name", "class", "level", "quality", "defense", "str", "dex", "wil",
  "toughMax", "powMax", "tough", "pow", "equipment",
}

-- Starting data for the per-model script: HERO_DEFAULTS, overlaid with
-- an existing hero's saved data when upgrading one.
local function buildDefaults(data)
  local d = {}
  for k, v in pairs(HERO_DEFAULTS) do d[k] = v end
  if type(data) ~= "table" then return d end
  for _, k in ipairs(STATE_KEYS) do
    local v = data[k]
    if type(v) == "string" or type(v) == "number" then d[k] = v end
  end
  if type(data.abilities) == "table" then
    d.abilities = {}
    for _, a in ipairs(data.abilities) do
      if type(a) == "table" and type(a.name) == "string" then
        table.insert(d.abilities, {
          name = a.name,
          desc = type(a.desc) == "string" and a.desc or "",
        })
      end
    end
  end
  return d
end

local function buildPerModelScript(data)
  local script = PER_MODEL_SCRIPT_TEMPLATE
  script = script:gsub("@@VERSION@@", tostring(SCRIPT_VERSION))
  script = script:gsub("@@DEFAULTS@@", gsubSafe(serialize(buildDefaults(data))))
  return script
end

-- Returns the customizer script version an object carries (1 for the
-- first release, which had no version line), or nil if its script
-- isn't one of ours. Plain find() only (MoonSharp pattern limits).
local CUSTOMIZER_MARKER = "generated by opr_hero_customizer.lua"
local VERSION_MARKER = "-- opr_hero_customizer script version: "

local function getCustomizerVersion(script)
  if not script or not script:find(CUSTOMIZER_MARKER, 1, true) then return nil end
  local idx = script:find(VERSION_MARKER, 1, true)
  if not idx then return 1 end
  return tonumber(script:match("^%d+", idx + #VERSION_MARKER)) or 1
end

-- ===== Assignment =====

local function assignTemplate(obj)
  obj.setLuaScript(buildPerModelScript(nil))
  obj.reload()
end

-- Replaces an older customizer script with the current one. The hero's
-- data is read from its saved state and baked in as the new script's
-- starting values, so it survives even if TTS drops the saved state
-- across the reload.
local function upgradeHero(obj, fromVersion)
  local data = nil
  local okState, saved = pcall(function() return obj.script_state end)
  if okState and type(saved) == "string" and saved ~= "" then
    local okDecode, decoded = pcall(JSON.decode, saved)
    if okDecode and type(decoded) == "table" then data = decoded end
  end
  local heroName = (data and type(data.name) == "string") and data.name or "a hero"
  obj.setLuaScript(buildPerModelScript(data))
  obj.reload()
  -- "(data carried by TTS)" = saved state wasn't readable up front, so
  -- the hero's data relies on TTS keeping it across the reload.
  print("Hero Customizer: updated " .. heroName .. " from script v" .. fromVersion ..
    " to v" .. SCRIPT_VERSION .. (data and "." or " (data carried by TTS)."))
end

local function forSelectedOrSelf(player_color, fallbackObj, fn)
  local selected = Player[player_color].getSelectedObjects()
  if #selected > 0 then
    for _, o in ipairs(selected) do fn(o) end
  else
    fn(fallbackObj)
  end
end

-- ===== Menu wiring / upgrades =====
-- Unscripted models get the "Assign Hero Template" menu. Models with an
-- older customizer script are upgraded. Anything else with a script
-- (opr_hero_assigner.lua heroes, workshop objects) is left alone.

local function handleObject(object)
  if ONLY_FIGURINES and not object.hasTag("Figurine") then return end
  local existingScript = object.getLuaScript()
  if existingScript and existingScript ~= "" then
    local version = getCustomizerVersion(existingScript)
    if version and version < SCRIPT_VERSION then
      local ok, err = pcall(upgradeHero, object, version)
      if not ok then
        print("Hero Customizer: update from script v" .. version .. " failed: " .. tostring(err))
      end
    end
    return
  end

  object.clearContextMenu()
  object.addContextMenuItem("Assign Hero Template", function(player_color)
    forSelectedOrSelf(player_color, object, function(o)
      -- Skip already-assigned models in a mixed selection so their
      -- edits aren't wiped back to defaults.
      local s = o.getLuaScript()
      if s == nil or s == "" then assignTemplate(o) end
    end)
  end)
end

-- Covers models already on the table when the save loads. Delayed
-- slightly so it runs after TTS has finished loading every object
-- (and applying any per-object scripts from the scripting editor),
-- rather than racing it.
function onLoad()
  -- Confirms in chat which version is actually running (the editor
  -- can show newer text than TTS is running if Save & Play failed).
  print("Hero Customizer Global loaded (script v" .. SCRIPT_VERSION .. ").")
  Wait.time(function()
    for _, obj in ipairs(getAllObjects()) do
      handleObject(obj)
    end
  end, 0.5)
end

-- ...and models spawned afterward (from a bag, spawnObject, etc.)
function onObjectSpawn(object)
  handleObject(object)
end
